"""Deterministic generation of standalone Contexture expert applications."""

from __future__ import annotations

import hashlib
import json
import keyword
import re
from dataclasses import dataclass
from pathlib import Path

from .models import ExpertBlueprint, RoleBlueprint, SkillBlueprint
from .workspace import Workspace


@dataclass(frozen=True, slots=True)
class BuildResult:
    project_id: str
    blueprint_id: str
    path: Path
    package: str
    artifact_sha256: str
    files: tuple[str, ...]
    unbound_required_tools: tuple[str, ...]


class ContextureGenerator:
    """Render a Blueprint without executing model-produced code."""

    def __init__(self, workspace: Workspace) -> None:
        self.workspace = workspace

    def build(self, blueprint: ExpertBlueprint) -> BuildResult:
        build_dir = (
            self.workspace.project_dir(blueprint.project_id)
            / "builds"
            / (f"v{blueprint.version:04d}-{blueprint.blueprint_id}")
        )
        package = _identifier(blueprint.name.replace("-", "_")) + "_expert"
        package_dir = build_dir / "src" / package
        package_dir.mkdir(parents=True, exist_ok=True)
        evidence = self.workspace.load_evidence(blueprint.project_id)
        bound = {item.requirement for item in blueprint.tool_bindings}
        unbound_required = tuple(
            item.name
            for item in blueprint.tool_requirements
            if item.required and item.name not in bound
        )
        files: dict[str, str] = {
            "pyproject.toml": _pyproject(blueprint, package),
            "README.md": _readme(blueprint, unbound_required),
            f"src/{package}/__init__.py": 'from .app import app\n\n__all__ = ["app"]\n',
            f"src/{package}/app.py": _application_source(blueprint),
            f"src/{package}/__main__.py": _runner_source(),
            f"src/{package}/evidence.json": json.dumps(
                evidence, ensure_ascii=False, indent=2, sort_keys=True
            )
            + "\n",
            "expert-blueprint.json": blueprint.model_dump_json(indent=2) + "\n",
        }
        for relative, content in files.items():
            path = build_dir / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
        digest = _tree_digest(files)
        manifest = {
            "schema_version": 1,
            "generator": "expertcompose-contexture-v1",
            "project_id": blueprint.project_id,
            "blueprint_id": blueprint.blueprint_id,
            "blueprint_sha256": blueprint.canonical_sha256(),
            "artifact_sha256": digest,
            "package": package,
            "files": sorted(files),
            "unbound_required_tools": list(unbound_required),
            "host_uses": list(_host_uses(blueprint)),
        }
        manifest_path = build_dir / "build-manifest.json"
        manifest_path.write_text(
            json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        return BuildResult(
            project_id=blueprint.project_id,
            blueprint_id=blueprint.blueprint_id,
            path=build_dir,
            package=package,
            artifact_sha256=digest,
            files=tuple(sorted((*files, "build-manifest.json"))),
            unbound_required_tools=unbound_required,
        )


def _application_source(blueprint: ExpertBlueprint) -> str:
    lines = [
        '"""Generated by ExpertCompose. Edit the Blueprint, not this file."""',
        "",
        "from __future__ import annotations",
        "",
        "import json",
        "import re",
        "from functools import cache",
        "from pathlib import Path",
        "",
        "from contexture import Contexture, Role, Skill, Tool",
        "",
        "",
        "@cache",
        "def _evidence() -> tuple[dict, ...]:",
        '    path = Path(__file__).with_name("evidence.json")',
        '    value = json.loads(path.read_text(encoding="utf-8"))',
        "    return tuple(value)",
        "",
        "",
        "class EvidenceLookup(Tool):",
        "    def __init__(self) -> None:",
        "        super().__init__(",
        '            name="lookup-evidence",',
        '            description=("Search bounded release evidence and return "',
        '                         "exact source locators."),',
        "            read_only=True,",
        "        )",
        "",
        "    async def invoke(self, query: str, limit: int = 5) -> dict:",
        "        if not query.strip():",
        '            raise ValueError("query must not be empty")',
        "        if not 1 <= limit <= 20:",
        '            raise ValueError("limit must be between 1 and 20")',
        '        terms = set(re.findall(r"[A-Za-z0-9_-]+|[\\u4e00-\\u9fff]", query.lower()))',
        "        ranked = []",
        "        for item in _evidence():",
        '            text = (str(item.get("summary", "")) + " " +',
        '                    str(item.get("excerpt", ""))).lower()',
        "            score = sum(text.count(term) for term in terms)",
        "            if score:",
        "                ranked.append((score, item))",
        '        ranked.sort(key=lambda pair: (-pair[0], pair[1]["evidence_id"]))',
        "        rows = []",
        "        for score, item in ranked[:limit]:",
        "            rows.append({",
        '                "evidence_id": item["evidence_id"],',
        '                "source_id": item["source_id"],',
        '                "locator": item["locator"],',
        '                "kind": item["kind"],',
        '                "summary": item["summary"],',
        '                "excerpt": str(item["excerpt"])[:1200],',
        '                "score": score,',
        "            })",
        '        return {"query": query, "count": len(rows), "results": rows}',
        "",
        "",
    ]
    roles = list(_walk_roles(blueprint.roots))
    internal_refs = _internal_refs(blueprint)
    for path, role in roles:
        for skill in role.skills:
            lines.extend(_skill_source(path, skill, internal_refs=internal_refs))
    for path, role in reversed(roles):
        lines.extend(_role_source(path, role, blueprint))
    root_classes = ", ".join(_role_class((root.name,)) for root in blueprint.roots)
    if len(blueprint.roots) == 1:
        root_classes += ","
    lines.extend(
        [
            "",
            "app = Contexture(",
            f"    name={blueprint.name!r},",
            f"    roots=({root_classes}),",
            ")",
            "",
            '__all__ = ["app"]',
            "",
        ]
    )
    return "\n".join(lines)


def _skill_source(
    path: tuple[str, ...], skill: SkillBlueprint, *, internal_refs: frozenset[str]
) -> list[str]:
    class_name = _skill_class((*path, skill.name))
    uses = tuple(ref for ref in skill.uses if ref in internal_refs)
    return [
        f"class {class_name}(Skill):",
        "    def __init__(self) -> None:",
        "        super().__init__(",
        f"            name={skill.name!r},",
        f"            description={skill.description!r},",
        f"            instructions={skill.instructions!r},",
        f"            uses={uses!r},",
        "        )",
        "",
        "",
    ]


def _role_source(
    path: tuple[str, ...], role: RoleBlueprint, blueprint: ExpertBlueprint
) -> list[str]:
    class_name = _role_class(path)
    children = ", ".join(_role_class((*path, child.name)) + "()" for child in role.children)
    skills = ", ".join(_skill_class((*path, skill.name)) + "()" for skill in role.skills)
    bindings = {item.requirement for item in blueprint.tool_bindings}
    tools = ", ".join(
        "EvidenceLookup()"
        for name in role.tool_requirements
        if name == "lookup-evidence" and name in bindings
    )
    return [
        f"class {class_name}(Role):",
        "    def __init__(self) -> None:",
        "        super().__init__(",
        f"            name={role.name!r},",
        f"            description={role.description!r},",
        f"            instructions={role.instructions!r},",
        f"            children=[{children}],",
        f"            skills=[{skills}],",
        f"            tools=[{tools}],",
        "        )",
        "",
        "",
    ]


def _walk_roles(
    roots: tuple[RoleBlueprint, ...], prefix: tuple[str, ...] = ()
) -> tuple[tuple[tuple[str, ...], RoleBlueprint], ...]:
    rows: list[tuple[tuple[str, ...], RoleBlueprint]] = []
    for role in roots:
        path = (*prefix, role.name)
        rows.append((path, role))
        rows.extend(_walk_roles(role.children, path))
    return tuple(rows)


def _internal_refs(blueprint: ExpertBlueprint) -> frozenset[str]:
    refs: set[str] = set()
    for path, role in _walk_roles(blueprint.roots):
        role_ref = "/".join(path)
        refs.add(role_ref)
        refs.update(f"{role_ref}/{skill.name}" for skill in role.skills)
    return frozenset(refs)


def _host_uses(blueprint: ExpertBlueprint) -> tuple[str, ...]:
    internal = _internal_refs(blueprint)
    return tuple(sorted({
        ref
        for _path, role in _walk_roles(blueprint.roots)
        for skill in role.skills
        for ref in skill.uses
        if ref not in internal
    }))


def _role_class(path: tuple[str, ...]) -> str:
    return "Role" + "".join(_pascal(part) for part in path)


def _skill_class(path: tuple[str, ...]) -> str:
    return "Skill" + "".join(_pascal(part) for part in path)


def _pascal(value: str) -> str:
    result = "".join(
        part[:1].upper() + part[1:] for part in re.split(r"[^A-Za-z0-9]+", value) if part
    )
    return result or "Node"


def _identifier(value: str) -> str:
    result = re.sub(r"\W", "_", value)
    if not result or result[0].isdigit() or keyword.iskeyword(result):
        result = "expert_" + result
    return result


def _pyproject(blueprint: ExpertBlueprint, package: str) -> str:
    distribution = blueprint.name + "-expert"
    return f'''[build-system]
requires = ["hatchling>=1.27"]
build-backend = "hatchling.build"

[project]
name = {distribution!r}
version = "0.{blueprint.version}.0"
description = {blueprint.title!r}
requires-python = ">=3.11"
dependencies = ["contexture-mcp>=1.0.0,<2"]

[project.scripts]
{blueprint.name}-expert = "{package}.__main__:main"

[tool.hatch.build.targets.wheel]
packages = ["src/{package}"]
artifacts = ["src/{package}/evidence.json"]
'''


def _readme(blueprint: ExpertBlueprint, unbound: tuple[str, ...]) -> str:
    warning = (
        "\n## Publication blockers\n\nRequired Tool bindings are missing: "
        + ", ".join(f"`{item}`" for item in unbound)
        + ".\n"
        if unbound
        else ""
    )
    host_uses = _host_uses(blueprint)
    host_warning = (
        "\n## Host composition dependencies\n\nThe embedding Host must provide these "
        "Contexture refs: " + ", ".join(f"`{item}`" for item in host_uses) + ".\n"
        if host_uses
        else ""
    )
    return f"""# {blueprint.title}

Generated by ExpertCompose from Blueprint `{blueprint.blueprint_id}`.

Objective: {blueprint.objective}

This project is a generated artifact. Change its source Blueprint and rebuild;
manual edits will be overwritten. Imported material remains evidence and does
not gain authority over the generated application.
{warning}{host_warning}
## Validate and serve

```bash
uv run {blueprint.name}-expert --check
uv run {blueprint.name}-expert
```
"""


def _runner_source() -> str:
    return '''"""Serve or validate this generated ExpertNet."""

from __future__ import annotations

import argparse

from contexture.core.model import SurfaceSelection
from contexture.server import ContextureOptions, HeaderSurfaceSelector, compile_application

from .app import app


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--transport", choices=("stdio", "streamable-http"), default="stdio")
    parser.add_argument("--port", type=int, default=8000)
    parser.add_argument("--select", action="append", default=[])
    args = parser.parse_args()
    compiled = compile_application(app)
    if args.check:
        print(f"valid: {len(tuple(compiled.index.walk()))} Contexture refs")
        return 0
    options = (
        ContextureOptions(transport="stdio")
        if args.transport == "stdio"
        else ContextureOptions(transport="streamable-http", port=args.port)
    )
    ceiling = (
        SurfaceSelection.only(tuple(args.select)).resolve(compiled.index)
        if args.select else SurfaceSelection.all()
    )
    server = compiled.server(
        surface_selector=HeaderSurfaceSelector(ceiling=lambda _principal: ceiling)
    )
    server.start(options)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''


def _tree_digest(files: dict[str, str]) -> str:
    digest = hashlib.sha256()
    for path in sorted(files):
        digest.update(path.encode())
        digest.update(b"\0")
        digest.update(files[path].encode())
        digest.update(b"\0")
    return digest.hexdigest()


